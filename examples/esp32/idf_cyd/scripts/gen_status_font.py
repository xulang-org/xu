#!/usr/bin/env python3
"""Generate xu/font.xu from the status_demo dashboard font (font.xu).

status_demo stores glyphs as code (one function per glyph), which costs about
185 KiB of Xtensa text. This emits the same font_bits/text_code/text_step API
over static hex tables (~8 KiB) for the IDF app, where flash is the limit.
"""
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO = ROOT.parents[2]
FONT = REPO / "examples/esp32/status_demo/font.xu"
OUT = ROOT / "xu/font.xu"

DUMP = """@main

#strconv

fn dump(code int) {
    $line := strconv.itoa(code)
    for row in 0:16 { line = line + " " + strconv.itoa(font_bits(code,row)) }
    println(line)
}

fn main() int {
    for c in 32:127 { dump(c) }
    cjk := [%s]
    for i in 0:cjk.len { dump(cjk[i]) }
    << 0
}
"""

TEMPLATE = """@main

// Generated by scripts/gen_status_font.py from
// examples/esp32/status_demo/font.xu; do not edit.
// 16 rows per glyph, MSB is the left pixel. ASCII 0x20..0x7e use the high
// byte (two hex digits per row); CJK glyphs are 16 bits (four per row),
// looked up by code point in FONT_CJK_CODES (sorted, four hex digits each).

const FONT_ASCII = "{ascii}"
const FONT_CJK_CODES = "{codes}"
const FONT_CJK = "{cjk}"

fn font_hex(data &string, at int, digits int) int {{
    $v := 0
    for i in 0:digits {{
        c := data[at + i]
        $d := c - 48
        if c >= 97 {{ d = c - 87 }}
        v = (v << 4) | d
    }}
    << v
}}
fn font_cjk_index(code int) int {{
    codes := FONT_CJK_CODES
    $lo := 0
    $hi := codes.len / 4 - 1
    while lo <= hi {{
        mid := (lo + hi) / 2
        value := font_hex(&codes,mid * 4,4)
        if value == code {{ << mid }}
        if value < code {{ lo = mid + 1 }} else {{ hi = mid - 1 }}
    }}
    << -1
}}
fn font_bits(code int, row int) int {{
    if row < 0 || row >= 16 {{ << 0 }}
    if code >= 32 && code < 127 {{
        ascii := FONT_ASCII
        << font_hex(&ascii,((code - 32) * 16 + row) * 2,2) << 8
    }}
    index := font_cjk_index(code)
    if index < 0 {{ << 0 }}
    cjk := FONT_CJK
    << font_hex(&cjk,(index * 16 + row) * 4,4)
}}
fn text_code(text &string, at int) int {{
    if at >= text.len {{ << 32 }}
    a := text[at]
    if a < 128 {{ << a }}
    if a >= 224 && a < 240 && at + 2 < text.len {{
        << ((a & 15) << 12) | ((text[at+1] & 63) << 6) | (text[at+2] & 63)
    }}
    << 63
}}
fn text_step(text &string, at int) int {{
    if at < text.len && text[at] >= 224 && text[at] < 240 && at + 2 < text.len {{ << 3 }}
    << 1
}}
"""


def main() -> int:
    xu = REPO / "bin/xu"
    cjk = sorted({int(c) for c in re.findall(r"fn glyph_(\d+)\(", FONT.read_text()) if int(c) >= 128})
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = pathlib.Path(tmp)
        (tmpdir / "dump.xu").write_text(DUMP % ",".join(map(str, cjk)))
        (tmpdir / "font.xu").write_text(FONT.read_text())
        exe = tmpdir / "dump"
        subprocess.check_call([str(xu), "build", str(tmpdir / "dump.xu"), str(tmpdir / "font.xu"), "-o", str(exe)])
        rows = [list(map(int, line.split())) for line in subprocess.check_output([str(exe)], text=True).splitlines()]

    ascii_rows = [r for r in rows if r[0] < 128]
    cjk_rows = [r for r in rows if r[0] >= 128]
    for r in ascii_rows:
        assert all(v & 0xFF == 0 for v in r[1:]), f"ASCII glyph {r[0]} uses the low byte"
    ascii_hex = "".join(f"{(v >> 8) & 0xFF:02x}" for r in ascii_rows for v in r[1:])
    codes_hex = "".join(f"{r[0]:04x}" for r in cjk_rows)
    cjk_hex = "".join(f"{v:04x}" for r in cjk_rows for v in r[1:])
    OUT.write_text(TEMPLATE.format(ascii=ascii_hex, codes=codes_hex, cjk=cjk_hex))
    print(f"wrote {OUT} ({len(ascii_rows)} ASCII, {len(cjk_rows)} CJK)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
