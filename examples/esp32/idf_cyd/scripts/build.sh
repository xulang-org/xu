#!/usr/bin/env bash
# Build idf_cyd against the pinned ESP-IDF and enforce the size gate.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$ROOT/../../.." && pwd)"
PIN="$(tr -d '[:space:]' < "$ROOT/IDF_VERSION")"
SIZE_LIMIT="${XU_IDF_CYD_SIZE_LIMIT:-1572864}" # 1.5 MiB soft gate

SSID=""
PASS=""
MQTT_URI="mqtt://192.168.1.10:1883"
ROOT_TOPIC="xu/esp32/cyd"
HID_NAME="XU-IDF-HID"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --ssid) SSID="$2"; shift 2 ;;
    --password) PASS="$2"; shift 2 ;;
    --mqtt-uri) MQTT_URI="$2"; shift 2 ;;
    --topic-root) ROOT_TOPIC="$2"; shift 2 ;;
    --hid-name) HID_NAME="$2"; shift 2 ;;
    --size-limit) SIZE_LIMIT="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

if [[ -z "${IDF_PATH:-}" ]]; then
  echo "IDF_PATH is unset. Install ESP-IDF $PIN and export the env." >&2
  exit 1
fi
got="$(cd "$IDF_PATH" && git describe --tags --exact-match 2>/dev/null || true)"
if [[ -n "$got" && "$got" != "$PIN" ]]; then
  echo "warning: IDF_PATH is $got, pin is $PIN" >&2
fi

# Local, gitignored provision fragment (never commit real credentials).
PROV="$ROOT/sdkconfig.provision"
umask 077
{
  echo "# Generated by scripts/build.sh — do not commit."
  if [[ -n "$SSID" ]]; then
    printf 'CONFIG_XU_WIFI_SSID="%s"\n' "$SSID"
  fi
  if [[ -n "$PASS" ]]; then
    printf 'CONFIG_XU_WIFI_PASSWORD="%s"\n' "$PASS"
  fi
  printf 'CONFIG_XU_MQTT_URI="%s"\n' "$MQTT_URI"
  printf 'CONFIG_XU_MQTT_ROOT="%s"\n' "$ROOT_TOPIC"
  printf 'CONFIG_XU_HID_NAME="%s"\n' "$HID_NAME"
} >"$PROV"
chmod 600 "$PROV"

export IDF_CCACHE_ENABLE="${IDF_CCACHE_ENABLE:-1}"
cd "$ROOT"
export SDKCONFIG_DEFAULTS="sdkconfig.defaults;sdkconfig.provision"
idf.py build

APP_BIN="$ROOT/build/xu_idf_cyd.bin"
if [[ ! -f "$APP_BIN" ]]; then
  APP_BIN="$(find "$ROOT/build" -maxdepth 1 -type f -name '*.bin' ! -name 'bootloader.bin' ! -name 'partition-table.bin' ! -name 'ota_data_initial.bin' | head -n1 || true)"
fi
if [[ -z "$APP_BIN" || ! -f "$APP_BIN" ]]; then
  echo "application binary not found under build/" >&2
  exit 1
fi
size="$(wc -c < "$APP_BIN" | tr -d ' ')"
echo "app binary: $APP_BIN ($size bytes)"
if (( size > SIZE_LIMIT )); then
  echo "size gate failed: $size > $SIZE_LIMIT" >&2
  exit 1
fi
echo "size gate ok (<= $SIZE_LIMIT)"
echo "$size" > "$ROOT/build/xu_idf_cyd_app_size.txt"
echo "repo=$REPO pin=$PIN size=$size" > "$ROOT/build/xu_idf_cyd_build_meta.txt"
