#!/usr/bin/env python3
"""Keep the Xu, Swift and C++ embedded WebView bridge identical to its JS source."""
import argparse
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    source=(ROOT/'src/ui/host/xu_webview_bridge.js').read_text()
    changes={}
    xu=ROOT/'src/ui/webview/mod.xu';text=xu.read_text()
    text=re.sub(r'pub fn bridge_script\(\) string \{.*?\n\}',lambda _: 'pub fn bridge_script() string {\n    // Generated from host/xu_webview_bridge.js.\n    << '+json.dumps(source,ensure_ascii=True)+'\n}',text,count=1,flags=re.S)
    changes[xu]=text
    swift=ROOT/'src/ui/host/macos_webview.swift';text=swift.read_text()
    text=re.sub(r'private let kXuBridgeJs = (?:#)?""".*?"""(?:#)?',lambda _: 'private let kXuBridgeJs = #"""\n'+source+'"""#',text,count=1,flags=re.S)
    changes[swift]=text
    changes[ROOT/'src/ui/host/xu_webview_bridge.inc']='// Generated by scripts/sync_ui_webview_bridge.py.\nstatic const char kXuBridgeJs[] = R"XUBRIDGE('+source+')XUBRIDGE";\n'
    bad=[]
    for path,content in changes.items():
        if path.exists() and path.read_text()==content: continue
        bad.append(str(path.relative_to(ROOT)))
        if not args.check: path.write_text(content)
    if args.check and bad: parser.error('stale embedded bridge: '+', '.join(bad))
    print('WebView bridge copies: '+('PASS' if args.check else 'synchronized'))
if __name__=='__main__':main()
