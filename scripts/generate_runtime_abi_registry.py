#!/usr/bin/env python3
"""Render the versioned ordinary-Xu runtime registry; --check rejects drift."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / 'src/runtime/ABI.json'
OUTPUT = ROOT / 'src/xu/types/runtime_abi_generated.xu'
SHAPES = {'int': 1, 'bool': 2, 'string': 3, 'borrow_string': 1003, 'int_array': 200}
EFFECTS = {'read': 1, 'write': 2, 'allocate': 4, 'free': 8, 'io': 16,
           'may_fail_loud': 32, 'may_block': 64, 'suspend': 128}

def validate(data: dict) -> list[dict]:
    if data.get('schema') != 1 or data.get('version') != 'xu-runtime-contracts-1':
        raise ValueError('unsupported registry schema/version')
    if data.get('effect_authority') != 'declared conservative upper bounds, not verified body facts or optimization permission':
        raise ValueError('effect declarations must not grant optimization permission')
    entries = data.get('entries')
    if not isinstance(entries, list) or not entries:
        raise ValueError('registry entries missing')
    ids, names, aliases = set(), set(), set()
    for row in entries:
        ident = row.get('id')
        if type(ident) is not int or ident <= 0 or ident in ids:
            raise ValueError('invalid/duplicate runtime ID')
        ids.add(ident)
        if row.get('abi') != 'xu_ordinary_v1' or row.get('module') != 'runtime':
            raise ValueError('this registry supports ordinary runtime Xu only')
        name = row.get('name', '')
        if not re.fullmatch(r'[a-z_][a-z_0-9]*', name) or name in names:
            raise ValueError('invalid/duplicate runtime name')
        names.add(name)
        if row.get('source') not in ('src/runtime/str_algo.xu', 'src/runtime/map_algo.xu') or row.get('inline_hint') != 'default':
            raise ValueError('unsupported source/inline policy')
        if not isinstance(row.get('params'), list) or not row['params']:
            raise ValueError('parameters must be a non-empty list')
        for param in row['params']:
            if param['shape'] not in ('int', 'borrow_string'):
                raise ValueError('unsupported parameter shape')
            want = 'borrow_noescape' if param['shape'] == 'borrow_string' else 'copy'
            if param['ownership'] != want:
                raise ValueError('parameter ownership conflicts with shape')
        result = row['result']
        if result['shape'] not in ('int', 'bool', 'string', 'int_array') or result['alias_of'] is not None:
            raise ValueError('unsupported result shape/alias')
        own = 'owned' if result['shape'] in ('string', 'int_array') else 'copy'
        if result['ownership'] != own:
            raise ValueError('result ownership conflicts with shape')
        if type(row['may_throw']) is not bool:
            raise ValueError('may_throw must be boolean')
        if set(row['effects']) != set(EFFECTS) or any(type(v) is not bool for v in row['effects'].values()):
            raise ValueError('effects must contain explicit boolean values')
        if not isinstance(row.get('syntax_aliases'), list) :
            raise ValueError('syntax aliases missing')
        for alias in row['syntax_aliases']:
            if not re.fullmatch(r'[a-z_][a-z_0-9]*', alias) or alias in aliases:
                raise ValueError('invalid/duplicate syntax alias')
            aliases.add(alias)
    return sorted(entries, key=lambda row: row['id'])

def registry_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'duplicate registry key: {key}')
        result[key] = value
    return result


def render(raw: bytes) -> str:
    rows = validate(json.loads(raw, object_pairs_hook=registry_object))
    lines = ['@xu/types', '// Generated by scripts/generate_runtime_abi_registry.py; edit src/runtime/ABI.json.',
             '// Registry SHA-256: ' + hashlib.sha256(raw).hexdigest(),
             '// IDs describe ordinary Xu contracts, never host/primitive authority.',
             '// Effects are declarations only; unknown IDs fail closed (-1).', '',
             'fn runtime_abi_name_eq(name &string, literal string) bool {',
             '    if name.len != literal.len { << false }',
             '    for i in 0:name.len { if name[i] != literal[i] { << false } }',
             '    << true', '}', '']
    def function(name, arg, branches, default, ret='int'):
        lines.append(f'pub fn {name}({arg}) {ret} {{')
        lines.extend('    ' + branch for branch in branches)
        lines.extend(['    << ' + default, '}', ''])
    function('runtime_abi_id', 'name &string', [f'if runtime_abi_name_eq(name, "{r["name"]}") {{ << {r["id"]} }}' for r in rows], '0')
    function('runtime_abi_syntax_id', 'name &string', [f'if runtime_abi_name_eq(name, "{a}") {{ << {r["id"]} }}' for r in rows for a in r['syntax_aliases']], '0')
    function('runtime_abi_name', 'id int', [f'if id == {r["id"]} {{ << "{r["name"]}" }}' for r in rows], '""', 'string')
    function('runtime_abi_source', 'id int', [f'if id == {r["id"]} {{ << "{r["source"]}" }}' for r in rows], '""', 'string')
    function('runtime_abi_count', '', [], str(len(rows)))
    function('runtime_abi_id_at', 'index int', [f'if index == {i} {{ << {r["id"]} }}' for i,r in enumerate(rows)], '0')
    function('runtime_abi_nparams', 'id int', [f'if id == {r["id"]} {{ << {len(r["params"])} }}' for r in rows], '-1')
    function('runtime_abi_param_shape', 'id int, index int', [f'if id == {r["id"]} && index == {i} {{ << {SHAPES[p["shape"]]} }}' for r in rows for i,p in enumerate(r['params'])], '-1')
    function('runtime_abi_result_shape', 'id int', [f'if id == {r["id"]} {{ << {SHAPES[r["result"]["shape"]]} }}' for r in rows], '-1')
    function('runtime_abi_throws', 'id int', [f'if id == {r["id"]} {{ << {int(r["may_throw"])} }}' for r in rows], '-1')
    function('runtime_abi_declared_effects', 'id int', [f'if id == {r["id"]} {{ << {sum(EFFECTS[k] for k,v in r["effects"].items() if v)} }}' for r in rows], '-1')
    return '\n'.join(lines)

def main():
    ap = argparse.ArgumentParser(description=__doc__);ap.add_argument('--check', action='store_true');args=ap.parse_args()
    expected=render(REGISTRY.read_bytes())
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text()!=expected:
            ap.exit(1,'runtime ABI: generated Xu registry differs; regenerate it\n')
        print('runtime ABI registry: PASS')
    else:
        OUTPUT.write_text(expected)
        print('Generated',OUTPUT.relative_to(ROOT))
if __name__ == '__main__': main()
