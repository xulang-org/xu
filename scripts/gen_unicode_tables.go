// Generate pinned Unicode 15.0.0 classification from Go's public APIs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strconv"
	"unicode"
)

// Two printable six-bit bytes encode a property mask or page number. The
// strings stay read-only on every Xu target and need no runtime allocation.
func packed12(values []uint16) string {
	out := make([]byte, len(values)*2)
	for i, value := range values {
		if value >= 4096 {
			panic("Unicode classification value exceeds 12 bits")
		}
		out[i*2] = byte(32 + (value >> 6))
		out[i*2+1] = byte(32 + (value & 63))
	}
	return string(out)
}

func main() {
	out := flag.String("out", "src/unicode/tables.xu", "output file")
	check := flag.Bool("check", false, "check without writing")
	flag.Parse()
	if unicode.Version != "15.0.0" {
		fmt.Fprintln(os.Stderr, "requires Unicode 15.0.0; found", unicode.Version)
		os.Exit(1)
	}
	properties := []func(rune) bool{
		unicode.IsDigit, unicode.IsLetter, unicode.IsSpace, unicode.IsUpper,
		unicode.IsLower, unicode.IsTitle, unicode.IsNumber, unicode.IsPunct,
		unicode.IsSymbol, unicode.IsPrint, unicode.IsGraphic, unicode.IsControl,
	}
	// Page zero is the all-false page. Assign IDs in codepoint order, rather
	// than map iteration order, so regenerating the file is deterministic.
	pages := make([]uint16, 256)
	ids := map[string]uint16{packed12(pages): 0}
	index := make([]uint16, (unicode.MaxRune+1)/256)
	for start := 0; start <= unicode.MaxRune; start += 256 {
		page := make([]uint16, 256)
		for offset := range page {
			for bit, predicate := range properties {
				if predicate(rune(start + offset)) {
					page[offset] |= 1 << bit
				}
			}
		}
		key := packed12(page)
		id, found := ids[key]
		if !found {
			if len(pages)/256 >= 4096 {
				panic("too many Unicode classification pages")
			}
			id = uint16(len(pages) / 256)
			ids[key] = id
			pages = append(pages, page...)
		}
		index[start/256] = id
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "@unicode\n\n// AUTO-GENERATED by scripts/gen_unicode_tables.go; Unicode 15.0.0.")
	fmt.Fprintln(&b, "// Go public predicates, derived from https://www.unicode.org/Public/15.0.0/ucd/ .")
	fmt.Fprintln(&b, "// 256-codepoint pages; two ASCII six-bit bytes per page ID / 12-bit mask.")
	fmt.Fprintln(&b, "// Bits: digit, letter, space, upper, lower, title, number, punct, symbol,")
	fmt.Fprintln(&b, "// print, graphic, control. Page zero is all false; IDs are deterministic.")
	fmt.Fprintf(&b, "// %d pages; index %d bytes; property data %d bytes.\n", len(pages)/256, len(index)*2, len(pages)*2)
	fmt.Fprintf(&b, "const classification_index = %s\n", strconv.Quote(packed12(index)))
	fmt.Fprintf(&b, "const classification_pages = %s\n", strconv.Quote(packed12(pages)))
	if *check {
		data, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(data, b.Bytes()) {
			os.Exit(1)
		}
	} else if err := os.WriteFile(*out, b.Bytes(), 0644); err != nil {
		panic(err)
	}
}
